let currentLanguage = 'bn';

export function getLanguage() {
  return currentLanguage;
}

export function setLanguage(lang) {
  if (lang !== 'bn' && lang !== 'en') lang = 'bn';
  currentLanguage = lang;
  try {
    localStorage.setItem('mondal_pujo_lang', lang);
  } catch (e) {}

  applyTranslations();
  return currentLanguage;
}

export function t(key) {
  const dict = translations[currentLanguage] || translations.bn;
  return dict[key] || translations.bn[key] || key;
}

export function applyTranslations() {
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (key) {
      const translated = t(key);
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        el.setAttribute('placeholder', translated);
      } else {
        el.innerHTML = translated;
      }
    }
  });

  // Update HTML lang attribute
  document.documentElement.lang = currentLanguage;

  // Dispatch global language change event
  window.dispatchEvent(new CustomEvent('pujo_language_changed', { detail: { lang: currentLanguage } }));
}
